/**
 * The applicant pool for the Senior AI Engineer role.
 *
 * Fifty people applied. Twenty are on the recruiter's shortlist and will be
 * called; thirty are not, and each of those carries the recruiter's reason in
 * their own words. The rejected thirty are seeded deliberately rather than
 * omitted, because a screening tool that only ever sees pre-filtered winners
 * teaches you nothing about the filter — and the filter is where most hiring
 * unfairness actually lives.
 *
 * The pool is built to contain the traps a keyword matcher falls into: a
 * marketing manager whose skills section is denser in AI terms than any real
 * engineer's, a researcher with better papers than anyone and no deployment, a
 * strong ranking engineer who never once writes the word "RAG". Whether the
 * shortlist got those calls right is a question a human can now argue with,
 * which is the point of shipping the reasons alongside the names.
 *
 * Every phone number is a US fiction-reserved 555-01xx line that can never
 * connect, including for the thirty who are not being called. India publishes
 * no reserved range, so a plausible +91 number committed to a public repository
 * is very likely someone's real phone. Two shortlisted entries have numbers
 * that cannot be resolved at all — that path matters as much as the happy one.
 */

