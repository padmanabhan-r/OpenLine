/** `"Python|expert|96|41"` → name, proficiency, months used, endorsements. */
function skills(specs: string[]): SkillEntry[] {
  return specs.map((spec) => {
    const [name, proficiency, months, endorsements] = spec.split("|");
    return {
      name: name.trim(),
      proficiency: proficiency.trim() as SkillEntry["proficiency"],
      durationMonths: Number(months),
      endorsements: Number(endorsements),
    };
  });
}

/**
 * A job, with its duration derived rather than restated.
 *
 * `period` is `"2022-04 → now"` or `"2019-07 → 2022-03"`. Writing the months
 * out by hand invites the arithmetic to drift from the dates, and a career
 * history that does not add up is the first thing a careful reader notices.
 */
function role(
  company: string,
  title: string,
  period: string,
  companySize: CompanySize,
  industry: string,
  description: string,
): CareerEntry {
  const [rawStart, rawEnd] = period.split("→").map((part) => part.trim());
  const isCurrent = rawEnd === "now";
  const startDate = `${rawStart}-01`;
  const endDate = isCurrent ? null : `${rawEnd}-01`;
  const end = isCurrent ? TODAY.slice(0, 7) : rawEnd;

  const [startYear, startMonth] = rawStart.split("-").map(Number);
  const [endYear, endMonth] = end.split("-").map(Number);
  const durationMonths = (endYear - startYear) * 12 + (endMonth - startMonth);

  return {
    company,
    title,
    startDate,
    endDate,
    durationMonths,
    isCurrent,
    industry,
    companySize,
    description,
  };
}

function edu(
  institution: string,
  degree: string,
  fieldOfStudy: string,
  years: string,
  grade: string | null,
  tier: EducationEntry["tier"],
): EducationEntry {
  const [startYear, endYear] = years.split("-").map(Number);
  return { institution, degree, fieldOfStudy, startYear, endYear, grade, tier };
}

function cert(name: string, issuer: string, year: number): CertificationEntry {
  return { name, issuer, year };
}

const ENGLISH: LanguageEntry = {
  language: "English",
  proficiency: "professional",
};

function langs(...others: Array<[string, LanguageEntry["proficiency"]]>) {
  return [
    ENGLISH,
    ...others.map(([language, proficiency]) => ({ language, proficiency })),
  ];
}

export interface ApplicantSeed extends CandidateProfile {
  /** Exactly as it arrived from the ATS import, malformed cases included. */
  rawPhone: string;
  email: string;
}

/**
 * Assemble a full record from the parts that vary.
 *
 * The current title, company, and company size are read off the first career
 * entry rather than restated, so a profile header can never contradict the
 * history beneath it.
 */
function applicant(input: {
  id: string;
  name: string;
  rawPhone: string;
  email: string;
  headline: string;
  summary: string;
  location: string;
  country?: string;
  yearsOfExperience: number;
  history: CareerEntry[];
  education: EducationEntry[];
  skillList: string[];
  certifications?: CertificationEntry[];
  languages?: LanguageEntry[];
  signals: PlatformSignals;
  appliedDate: string;
  shortlisted: boolean;
  matchScore: number;
  note: string;
}): ApplicantSeed {
  const current = input.history[0];

  return {
    candidateId: input.id,
    rawPhone: input.rawPhone,
    email: input.email,
    profile: {
      anonymizedName: input.name,
      headline: input.headline,
      summary: input.summary,
      location: input.location,
      country: input.country ?? "India",
      yearsOfExperience: input.yearsOfExperience,
      currentTitle: current.title,
      currentCompany: current.company,
      currentCompanySize: current.companySize,
      currentIndustry: current.industry,
    },
    careerHistory: input.history,
    education: input.education,
    skills: skills(input.skillList),
    certifications: input.certifications ?? [],
    languages: input.languages ?? [ENGLISH],
    signals: input.signals,
    screening: {
      appliedDate: input.appliedDate,
      shortlisted: input.shortlisted,
      matchScore: input.matchScore,
      note: input.note,
    },
  };
}

